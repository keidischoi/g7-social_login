    /** 원형 아이콘 SVG 문서 */
    public static function svg(string $provider): string
    {
        $body = self::bodies()[$provider] ?? '<circle cx="24" cy="24" r="24" fill="#9CA3AF"/>';
        $s = self::SIZE;

        return '<svg xmlns="http://www.w3.org/2000/svg" width="'.$s.'" height="'.$s.'" viewBox="0 0 '.$s.' '.$s.'">'.$body.'</svg>';
    }

    public static function dataUri(string $provider): string
    {
        return 'data:image/svg+xml;base64,'.base64_encode(self::svg($provider));
    }

